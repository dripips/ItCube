<?php

namespace App\Support;

/**
 * Дни недели.
 *
 * Названия возвращаются уже переведёнными и записаны литералами: извлекатель
 * строк ищет их прямо в коде, и подстановка через массив делала бы дни
 * невидимыми для проверки словарей.
 *
 * Нумерация от единицы — понедельник, как в ISO и как в школьном расписании.
 */
final class Week
{
    /** @var list<int> */
    public const DAYS = [1, 2, 3, 4, 5, 6, 7];

    public static function name(int $day): string
    {
        return match ($day) {
            1 => __('Понедельник'),
            2 => __('Вторник'),
            3 => __('Среда'),
            4 => __('Четверг'),
            5 => __('Пятница'),
            6 => __('Суббота'),
            7 => __('Воскресенье'),
            default => '—',
        };
    }

    public static function short(int $day): string
    {
        return match ($day) {
            1 => __('Пн'),
            2 => __('Вт'),
            3 => __('Ср'),
            4 => __('Чт'),
            5 => __('Пт'),
            6 => __('Сб'),
            7 => __('Вс'),
            default => '—',
        };
    }
}
